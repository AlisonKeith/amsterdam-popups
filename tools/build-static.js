// ---- category pages ----
// A category with no events this week still gets its page (stable URL, "nothing this week" note),
// but it is marked noindex and left out of the sitemap, llms.txt and the footer links.
function catPage(c, L){
  const evs = inCat(c.id), T = TXT[L], label = c.label[L];
  return listPage({
    L, url:catPath(c.id, L), currentId:c.id,
    title:T.catTitle(label, week.label[L]),
    desc:T.catDesc(label, evs.length, week.label[L]),
    robots:evs.length ? "" : "noindex, follow",
    headerExtra:` · <a href="${L === "nl" ? "/nl/deze-week.html" : "/this-week.html"}">${T.allWeek}</a>`,
    h1:T.catH1(label),
    lead:`  <p>${esc(week.label[L])} · ${T.count(evs.length)}</p>\n  <p>${esc(CAT_PAGES[c.id][L].intro)} ${T.check}</p>`,
    events:evs, ld:jsonLd(evs, L)
  });
}

