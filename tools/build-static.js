// The JSON-LD helpers (SCHEMA_TYPE, schemaPlace, schemaOffer) are taken from index.html itself,
// so the static pages and the live page describe events the same way.
const schemaSrc = (() => {
  const a = html.indexOf("const SCHEMA_TYPE = {"), b = html.indexOf("function injectEventSchema(){");
  if(a < 0 || b < a) throw new Error("JSON-LD helpers not found in index.html");
  return html.slice(a, b);
})();
const {SCHEMA_TYPE, schemaPlace, schemaOffer} = Function(`"use strict"; ${schemaSrc}; return {SCHEMA_TYPE, schemaPlace, schemaOffer};`)();

